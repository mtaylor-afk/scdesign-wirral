// WV Roofing — the estimate step's figures for the three sample houses.
//
//   node scripts/wvroofing/gen-sample-estimates.mjs          rewrite public/WVROOFING/samples/estimates.json
//   node scripts/wvroofing/gen-sample-estimates.mjs --check  exit 1 if the committed file is out of date
//
// A sample house has no project and no measurement, so the estimate step had nothing to
// show. Each sample now carries EXAMPLE roof faces (typical for its kind of house, not
// measured), and the quantities are worked out here, on the server's own code
// (quantities.js) and the draft specifications, so the browser only displays them. The
// page labels them as example figures. Re-run after any change to products.json.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(import.meta.url);
const quantities = require(path.join(repo, "serverlib/wvroofing/quantities.js"));
const { tooShallow } = require(path.join(repo, "serverlib/wvroofing/measurements.js"));
const { wholeM2 } = require(path.join(repo, "serverlib/wvroofing/measure/geometry.js"));
const visuals = JSON.parse(fs.readFileSync(path.join(repo, "public/WVROOFING/data/catalogue.json"), "utf8")).visuals;
const samples = JSON.parse(fs.readFileSync(path.join(repo, "public/WVROOFING/samples/samples.json"), "utf8")).samples;

// Example faces: on-the-slope areas in m² and pitches in degrees, typical for each kind of house.
const EXAMPLE_ROOFS = {
  "semi-1930s": [
    { id: "front", surface_m2: 26, pitch_deg: 40 },
    { id: "rear", surface_m2: 26, pitch_deg: 40 },
    { id: "hip end", surface_m2: 12, pitch_deg: 40 },
  ],
  "detached-modern": [
    { id: "front", surface_m2: 46, pitch_deg: 30 },
    { id: "rear", surface_m2: 46, pitch_deg: 30 },
  ],
  "detached-clay": [
    { id: "front", surface_m2: 38, pitch_deg: 45 },
    { id: "rear", surface_m2: 38, pitch_deg: 45 },
    { id: "front gable", surface_m2: 9, pitch_deg: 45 },
  ],
};

const NOT_INCLUDED_WORDS = { ridge: "ridges", hip: "hips", valley: "valleys", eaves: "eaves", verge: "verges", abutment: "abutments" };

export function build() {
  const out = {};
  for (const s of samples) {
    const faces = EXAMPLE_ROOFS[s.id];
    if (!faces) throw new Error("no example roof for sample " + s.id);
    const m = { faces: faces.map((f) => Object.assign({ included: true }, f)), edges: [] };
    const pitches = [...new Set(faces.map((f) => f.pitch_deg))].sort((a, b) => a - b);
    const byVisual = {};
    for (const v of visuals) {
      const ests = quantities.estimateForVisual(m, v.id, { drafts: true });
      const notIncluded = new Set();
      for (const e of ests) for (const n of e.not_included) notIncluded.add(NOT_INCLUDED_WORDS[n.item] || n.item);
      byVisual[v.id] = {
        products: ests.map((e) => ({
          name: e.product_name,
          unit: e.unit,
          draft: e.spec_status !== "verified",
          complete: e.complete,
          too_shallow: tooShallow(e),
          total: e.total ? { units: e.total.units, allowance_pct: e.total.allowance_pct, packs: e.total.packs, pack_size: e.total.pack_size, pack_name: e.total.pack_name } : null,
          linear: [],
          warnings: e.warnings,
        })),
        not_included: [...notIncluded],
      };
    }
    out[s.id] = {
      measurement: {
        area_m2: wholeM2(faces.reduce((n, f) => n + f.surface_m2, 0)),
        faces: faces.length,
        pitch: pitches.length === 1 ? pitches[0] + "°" : pitches[0] + "–" + pitches[pitches.length - 1] + "°",
        label: "Example figures for this sample house, typical for its kind: not a measurement",
        changes_since_year: null,
      },
      byVisual,
    };
  }
  return {
    note: "Generated by scripts/wvroofing/gen-sample-estimates.mjs from products.json (draft specifications) and example roof faces. Do not edit by hand.",
    samples: out,
  };
}

const file = path.join(repo, "public/WVROOFING/samples/estimates.json");
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = JSON.stringify(build(), null, 2) + "\n";
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (have !== want) {
      console.error("public/WVROOFING/samples/estimates.json is out of date: run node scripts/wvroofing/gen-sample-estimates.mjs");
      process.exit(1);
    }
    console.log("sample estimates up to date");
  } else {
    fs.writeFileSync(file, want);
    console.log("wrote " + path.relative(repo, file));
  }
}
